let current = "en";
export function localeInfo(code = current) {
  return LOCALES.find((locale) => locale.code === code) || LOCALES[0];
}

/** Map a BCP 47 tag (zh-TW, ar-EG, fr-CA…) to one of our locales. */
function resolveLocale(tag) {
  if (!tag) return null;
  const lower = String(tag).toLowerCase();
  if (lower === "zh-tw" || lower === "zh-hk" || lower === "zh-mo" || lower.startsWith("zh-hant"))
    return "zh-Hant";
  if (lower.startsWith("zh")) return "zh-Hans";
  if (lower.startsWith("ar")) return "ar";
  if (lower.startsWith("fr")) return "fr";
  if (lower.startsWith("ru")) return "ru";
  if (lower.startsWith("es")) return "es";
  if (lower.startsWith("en")) return "en";
  return null;
}

function detectLocale() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && MESSAGES[stored]) return stored;
  const candidates =
    Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language];
  for (const tag of candidates) {
    const resolved = resolveLocale(tag);
    if (resolved) return resolved;
  }
  return "en";
}

export function getLocale() {
  return current;
}

export function t(key, vars) {
  const table = MESSAGES[current] || {};
  let text = table[key] ?? MESSAGES.en[key] ?? key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (match, name) =>
      vars[name] !== undefined ? String(vars[name]) : match,
    );
  }
  return text;
}

function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.title = t(element.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  });
}

export function setLocale(code, { persist = true, silent = false } = {}) {
  const next = MESSAGES[code] ? code : "en";
  const changed = next !== current;
  current = next;
  if (persist) localStorage.setItem(STORAGE_KEY, next);
  document.documentElement.lang = next;
  document.documentElement.dir = localeInfo(next).dir;
  applyTranslations();
  document.querySelectorAll("[data-lang-label]").forEach((label) => {
    label.textContent = localeInfo(next).name;
  });
  if (changed && !silent) {
    document.dispatchEvent(new CustomEvent("localechange", { detail: { locale: next } }));
  }
  return next;
}

export function initI18n() {
  return setLocale(detectLocale(), { persist: false, silent: true });
}
